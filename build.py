"""Build a landing page folder from its src/.

Each page folder has page.json ({"title", "section", "template", "section_name",
optional "settings": [{"id", "label", "info"}]}). Every [[setting_id]] token in
src/page.html becomes {{ section.settings.setting_id }} in Shopify (editable in the
theme editor) and an empty string in the preview.
and src/page.html, src/page.css, src/page.js. Writes into that folder:
  preview/index.html                       local preview (no cart)
  shopify/sections/<section>.liquid        Shopify section
  shopify/templates/page.<template>.json   page template using it

Usage: python3 build.py <page-folder> [<page-folder> ...]
"""
import json
import sys
from pathlib import Path

CDN = "https://cdn.shopify.com/s/files/1/0647/7696/2256/files/"
FONT_FACES = """@font-face {{ font-family: 'TPM Lemon'; src: url({lemon}) format('woff2'); font-weight: 700; font-display: swap; }}
@font-face {{ font-family: 'TPM Sofia'; src: url('{cdn}Sofia_Pro_Regular_Az.woff2?v=1757613796') format('woff2'); font-weight: 400; font-display: swap; }}
@font-face {{ font-family: 'TPM Sofia'; src: url('{cdn}Sofia_Pro_Semi_Bold_Az.woff2?v=1757613796') format('woff2'); font-weight: 600; font-display: swap; }}
@font-face {{ font-family: 'TPM Condensed'; src: url('{cdn}Coolvetica_Hv_Comp.woff2?v=1758909708') format('woff2'); font-weight: 400; font-display: swap; }}
"""

PREVIEW_SHELL = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} (preview)</title>
<meta name="robots" content="noindex">
{head_links}
<style>
{fonts}
body {{ margin: 0; background: #fff; }}
.pv-bar {{ background: #000; color: #fff; font: 600 12px/1.4 system-ui, sans-serif; text-align: center; padding: 6px 12px; }}
.pv-header {{ display: flex; align-items: center; justify-content: space-between; padding: 12px 20px; border-bottom: 1px solid #eee; }}
.pv-header img {{ height: 28px; width: auto; }}
.pv-header a {{ font: 600 14px/1 system-ui, sans-serif; color: #000; }}
.pv-footer {{ background: #000; color: #fff; padding: 32px 20px; font: 14px/1.6 system-ui, sans-serif; }}
.pv-footer a {{ color: #fff; margin-right: 16px; }}
{css}
</style>
</head>
<body>
<div class="pv-bar">Local preview. The store's real header, footer and cart drawer replace the parts outside the page section.</div>
<header class="pv-header">
  <a href="https://gettipsy.com/"><img src="https://gettipsy.com/cdn/shop/files/TIPSY_AF_Logo_Header.png?width=200" width="200" height="72" alt="TIPSY AF"></a>
  <a href="https://gettipsy.com/pages/contact">Contact Us</a>
</header>
<main>
{html}
</main>
<footer class="pv-footer">
  <a href="https://gettipsy.com/pages/returns-refunds-policy">Returns &amp; Refunds</a>
  <a href="https://gettipsy.com/pages/terms-of-service">Terms of Service</a>
  <a href="https://gettipsy.com/pages/privacy-policy">Privacy Policy</a>
  <p>&copy;2026 TIPSY Beverages LLC.</p>
</footer>
<script>
{js}
</script>
</body>
</html>
"""

SECTION_SCHEMA = """{{% schema %}}
{{
  "name": "{name}",
  "tag": "section",
  "class": "section-{section}",
  "settings": {settings},
  "presets": [{{ "name": "{name}" }}]
}}
{{% endschema %}}
"""

TEMPLATE_JSON = """{{
  "sections": {{
    "main": {{
      "type": "{section}",
      "settings": {{}}
    }}
  }},
  "order": ["main"]
}}
"""


def build(root):
    cfg = json.loads((root / "page.json").read_text())
    SRC = root / "src"
    ROOT = root
    html = (SRC / "page.html").read_text()
    css = (SRC / "page.css").read_text()
    js = (SRC / "page.js").read_text()

    settings = cfg.get("settings", [])
    liquid_html = html
    for st in settings:
        token = "[[" + st["id"] + "]]"
        html = html.replace(token, "")
        liquid_html = liquid_html.replace(token, "{{ section.settings." + st["id"] + " | escape }}")
    schema_settings = json.dumps([dict(type="text", **st) for st in settings], indent=4)
    preview_html = html.replace('<div class="tpm" id="tpm">', '<div class="tpm" id="tpm" data-tpm-mode="preview">', 1)
    # Relative store links point at the live store in the preview.
    preview_html = preview_html.replace('href="/', 'href="https://gettipsy.com/')
    preview_fonts = FONT_FACES.format(
        lemon="'https://gettipsy.com/cdn/shop/t/13/assets/lemonmilk-bold.woff2'", cdn=CDN)
    out = ROOT / "preview" / "index.html"
    out.parent.mkdir(exist_ok=True)
    links = "".join('<link rel="stylesheet" href="%s">\n' % u for u in cfg.get("stylesheets", []))
    out.write_text(PREVIEW_SHELL.format(title=cfg["title"], head_links=links, fonts=preview_fonts, css=css, html=preview_html, js=js))

    liquid_fonts = FONT_FACES.format(lemon="{{ 'lemonmilk-bold.woff2' | asset_url }}", cdn=CDN)
    section = ("{%- comment -%} Generated by build.py from " + root.name + "/src. Edit src/ and rebuild. {%- endcomment -%}\n"
               + links
               + "<style>\n" + liquid_fonts + css + "</style>\n\n"
               + liquid_html + "\n<script>\n" + js + "</script>\n\n"
               + SECTION_SCHEMA.format(name=cfg["section_name"], section=cfg["section"], settings=schema_settings))
    sec = ROOT / "shopify" / "sections" / (cfg["section"] + ".liquid")
    sec.parent.mkdir(parents=True, exist_ok=True)
    sec.write_text(section)

    tpl = ROOT / "shopify" / "templates" / ("page." + cfg["template"] + ".json")
    tpl.parent.mkdir(parents=True, exist_ok=True)
    tpl.write_text(TEMPLATE_JSON.format(section=cfg["section"]))
    print(root.name + ":", out.relative_to(ROOT), sec.relative_to(ROOT), tpl.relative_to(ROOT))


if __name__ == "__main__":
    folders = sys.argv[1:]
    if not folders:
        sys.exit("usage: python3 build.py <page-folder> [...]")
    for f in folders:
        build(Path(f).resolve())
